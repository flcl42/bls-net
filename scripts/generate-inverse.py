"""Expand blst's 31-bit binary-GCD matrices into fixed-offset C# limb code.

Run from the repository root. Algorithm/schedule: ct_inverse_mod_256-x86_64.pl
(including its Python reference), no_asm.h and recip.c in pinned external/blst.
The 384-bit x86 kernel lives in ctx_inverse_mod_384-x86_64.pl in this blst revision.
"""
from pathlib import Path

root = Path('src/Nethermind.Crypto.BlsNet/Arithmetic')
opt = '[MethodImpl(MethodImplOptions.NoInlining | MethodImplOptions.AggressiveOptimization)]'
inline = '[MethodImpl(MethodImplOptions.AggressiveInlining)]'

for name, n, modulus, align in [
    ('Fp', 6, int('1a0111ea397fe69a4b1ba7b6434bacd764774b84f38512bf6730d2a0f6b0f6241eabfffeb153ffffb9feffffffffaaab', 16), 3),
    ('Fr', 4, int('73eda753299d7d483339d80809a1d80553bda402fffe5bfeffffffff00000001', 16), 1),
]:
    batches = 2*n*64//31 - (1 if name == 'Fr' else 0)
    remaining = 2*n*64 - 31*batches
    lines = []
    def w(s=''): lines.extend(s.split('\n'))
    def args(prefix, size=n): return ', '.join(f'{prefix}{i}' for i in range(size))
    def construct(prefix): return f'new {name}({args(prefix)})'
    def chain(dest, source, operation, carry, size=n):
        for i in range(size): w(f'        {dest}{i} = {operation}({source(i)}, ref {carry});')

    w('// Ported from blst, copyright Supranational LLC, Apache-2.0.\n// Generated by scripts/generate-inverse.py; see docs/design.md for invariants.\nusing System.Numerics;\nusing System.Runtime.CompilerServices;\n\nnamespace Nethermind.Crypto.BlsNet.Arithmetic;\n')
    w(f'public readonly partial struct {name}\n{{')
    w('    /// <summary>Secret inverse using fixed blst binary-GCD batches. Zero maps to zero; permits aliases.</summary>')
    w(f'    {opt}\n    public static void InverseConstantTime(out {name} result, in {name} value)\n    {{')
    w(f'        {name} a = value, b = new({args("M")});')
    w('        InverseWide u = new() { L0 = 1 }, v = default;')
    w(f'        // {batches} batches of 31, then {remaining} exact steps: {2*n*64} total.\n        for (int batch = 0; batch < {batches}; batch++)\n        {{')
    w('            InverseApproximate(a, b, out ulong aa, out ulong bb);\n            InverseBatch.Steps31(aa, bb, out long f0, out long g0, out long f1, out long g1);')
    w(f'            InverseUpdate(out {name} nextA, a, b, ref f0, ref g0);\n            InverseUpdate(out b, a, b, ref f1, ref g1);\n            a = nextA;\n            InverseCoefficient(out InverseWide nextU, u, v, f0, g0);\n            InverseCoefficient(out v, u, v, f1, g1);\n            u = nextU;\n        }}')
    w(f'        InverseBatch.Finish(a._l0, b._l0, {remaining}, out long f, out long g);\n        long top = InverseCoefficient(out v, u, v, f, g);\n        InverseCorrect(out result, v, top);\n    }}\n')
    w(f'    {opt}\n    internal static void InverseApproximate(in {name} a, in {name} b, out ulong aa, out ulong bb)\n    {{')
    w(f'        ulong ah = a._l{n-1}, al = a._l{n-2}, bh = b._l{n-1}, bl = b._l{n-2}, mask;')
    for i in range(n-3,-1,-1):
        w(f'        mask = InverseBatch.ZeroMask(ah | bh);\n        ah = InverseBatch.Select(al, ah, mask); bh = InverseBatch.Select(bl, bh, mask);\n        al = InverseBatch.Select(a._l{i}, al, mask); bl = InverseBatch.Select(b._l{i}, bl, mask);')
    w('        mask = InverseBatch.ZeroMask(ah | bh);\n        int shift = BitOperations.LeadingZeroCount(ah | bh) & 63;\n        ah = InverseBatch.Select(a._l0, ah, mask); bh = InverseBatch.Select(b._l0, bh, mask);\n        ulong shifted = ~InverseBatch.ZeroMask((ulong)shift);\n        aa = ((ah << shift) | ((al & shifted) >> (-shift & 63))) & 0xffffffff80000000;\n        bb = ((bh << shift) | ((bl & shifted) >> (-shift & 63))) & 0xffffffff80000000;\n        aa |= a._l0 & 0x7fffffff; bb |= b._l0 & 0x7fffffff;\n    }\n')
    w(f'    {opt}\n    internal static void InverseUpdate(out {name} result, in {name} a, in {name} b, ref long f, ref long g)\n    {{\n        long carry = 0;')
    for i in range(n): w(f'        carry = InverseProduct(out ulong t{i}, f, a._l{i}, g, b._l{i}, carry);')
    w(f'        ulong t{n} = (ulong)carry;\n        ulong mask = (ulong)(carry >> 63);\n        f = (f ^ (long)mask) - (long)mask; g = (g ^ (long)mask) - (long)mask;\n        ulong c = mask & 1;')
    for i in range(n): w(f'        ulong r{i} = AddCarry(((t{i} >> 31) | (t{i+1} << 33)) ^ mask, 0, ref c);')
    w(f'        result = {construct("r")};\n    }}\n')
    w(f'    {opt}\n    internal static long InverseCoefficient(out InverseWide result, in InverseWide u, in InverseWide v, long f, long g)\n    {{\n        long carry = 0;')
    for i in range(2*n): w(f'        carry = InverseProduct(out ulong t{i}, f, u.L{i}, g, v.L{i}, carry);')
    w(f'        // Sign-extend the two wide operands beyond their stored limbs.\n        carry -= f & ((long)u.L{2*n-1} >> 63);\n        carry -= g & ((long)v.L{2*n-1} >> 63);')
    for i in range(2*n): w(f'        result.L{i} = t{i};')
    w('        return carry;\n    }\n')
    w(f'    {inline}\n    private static long InverseProduct(out ulong low, long f, ulong a, long g, ulong b, long carry)\n    {{\n        ulong high = MulAdd((ulong)f, a, (ulong)carry, 0, out low);\n        high -= a & (ulong)(f >> 63);\n        high += (ulong)(carry >> 63);\n        high += MulAdd((ulong)g, b, low, 0, out low) - (b & (ulong)(g >> 63));\n        return (long)high;\n    }}\n')
    w(f'    {opt}\n    internal static void InverseCorrect(out {name} result, in InverseWide value, long top)\n    {{\n        // blst modx: modulus left-aligned within one field width. The final\n        // cofactor lies in [-2^(2N),2^(2N)]; top is -1, 0 or 1.\n        ulong sign = (ulong)(top >> 63), c = 0;')
    xs = [(modulus << align >> (64*i)) & (2**64-1) for i in range(n)]
    for i,x in enumerate(xs): w(f'        const ulong X{i} = 0x{x:016x}UL;')
    for i in range(n): w(f'        ulong h{i} = AddCarry(value.L{n+i}, X{i} & sign, ref c);')
    w('        top += (long)c;\n        ulong adjust = ~InverseBatch.ZeroMask((ulong)top);\n        sign = (ulong)(-top >> 63);\n        c = sign & 1;')
    for i in range(n): w(f'        ulong x{i} = AddCarry((X{i} & adjust) ^ sign, 0, ref c);')
    w('        c = 0;')
    for i in range(n): w(f'        h{i} = AddCarry(h{i}, x{i}, ref c);')
    w('        // Corrected value is in [0,R^2). Canonicalize its high half\n        // before REDC, so the sum with REDC(low) is below 2*modulus.')
    for bit in reversed(range(align+1)):
        w('        ulong borrow' + str(bit) + ' = 0;')
        for i in range(n):
            x=(modulus<<bit>>(64*i)) & (2**64-1)
            w(f'        ulong s{bit}_{i} = SubBorrow(h{i}, 0x{x:016x}UL, ref borrow{bit});')
        w(f'        ulong mask{bit} = borrow{bit} - 1;')
        for i in range(n): w(f'        h{i} = InverseBatch.Select(s{bit}_{i}, h{i}, mask{bit});')
    for i in range(n): w(f'        ulong t{i} = value.L{i};')
    w(f'        for (int row = 0; row < {n}; row++)\n        {{\n            ulong q = t0 * N0;\n            ulong carry = MulAdd(q, M0, t0, 0, out _);')
    for i in range(1,n): w(f'            carry = MulAdd(q, M{i}, t{i}, carry, out t{i-1});')
    w(f'            t{n-1} = carry;\n        }}\n        c = 0;')
    for i in range(n): w(f'        h{i} = AddCarry(h{i}, t{i}, ref c);')
    w(f'        Reduce(out {name} reduced, {args("h")});')
    r2 = 'R2' if name=='Fp' else 'new Fr(0xc999e990f3f29c6d, 0x2b6cedcb87925c23, 0x05d314967254398f, 0x0748d9d99f59ff11)'
    w(f'        // T=2N steps give v*input=R^2 modulo the modulus. REDC then\n        // multiplication by R^2 restores the inverse Montgomery representation.\n        Multiply(out result, reduced, {r2});\n    }}\n')
    w('    internal struct InverseWide\n    {')
    for i in range(2*n): w(f'        internal ulong L{i};')
    w('    }\n}')
    (root / f'{name}.InverseConstantTime.cs').write_text('\n'.join(lines)+'\n')
