"""Expand the pinned blst x86 binary-GCD schedule into C# carry rows.

Run from the repository root. See ctx_inverse_mod_384-x86_64.pl,
ct_inverse_mod_256-x86_64.pl, no_asm.h, recip.c and docs/design.md.
"""
from pathlib import Path

root = Path('src/Nethermind.Crypto.BlsNet/Arithmetic')
opt = '[MethodImpl(MethodImplOptions.NoInlining | MethodImplOptions.AggressiveOptimization)]'
inline = '[MethodImpl(MethodImplOptions.AggressiveInlining)]'

for name, n, modulus, align in [
    ('Fp', 6, int('1a0111ea397fe69a4b1ba7b6434bacd764774b84f38512bf6730d2a0f6b0f6241eabfffeb153ffffb9feffffffffaaab', 16), 3),
    ('Fr', 4, int('73eda753299d7d483339d80809a1d80553bda402fffe5bfeffffffff00000001', 16), 1),
]:
    batches = 2*n*64//31 - 1
    remaining = 2*n*64 - 31*batches
    narrow_last = 11 if name == 'Fp' else 8
    lines = []
    def w(s=''): lines.extend(s.split('\n'))
    def args(prefix, size=n): return ', '.join(f'{prefix}{i}' for i in range(size))
    def constructor(prefix, words=n): return f'new {name}({args(prefix, words)}' + ', 0'*(n-words) + ')'

    def negate(prefix, load, count, factor, signed):
        w(f'        ulong {prefix}Mask = (ulong)({factor} >> 63);')
        w(f'        ulong {prefix}Factor = ((ulong){factor} ^ {prefix}Mask) - {prefix}Mask;')
        w(f'        ulong {prefix}Carry = {prefix}Mask & 1;')
        for i in range(count): w(f'        ulong {prefix}{i} = AddCarry({load(i)} ^ {prefix}Mask, 0, ref {prefix}Carry);')
        sign = f'(ulong)((long){load(count-1)} >> 63)' if signed else '0UL'
        w(f'        long {prefix}Extension = (long)(({sign} ^ {prefix}Mask) + {prefix}Carry);')

    def sum_products(ucount, vcount, result_count, load_u, load_v, signed, need_top):
        # Negate the input by the multiplier sign, then use its absolute value
        # in complete unsigned MulAdd rows. The second row accumulates the first.
        negate('x', load_u, ucount, 'f', signed)
        w('        ulong carry = 0;')
        for i in range(ucount):
            if i == ucount-1 and not need_top:
                w(f'        ulong p{i} = xFactor * x{i} + carry;')
            else:
                w(f'        carry = MulAdd(xFactor, x{i}, 0, carry, out ulong p{i});')
        if need_top:
            w('        long xTop = (long)carry + (long)xFactor * xExtension;')
            for i in range(ucount, result_count):
                w(f'        ulong p{i} = (ulong)xTop;' if i == ucount else f'        ulong p{i} = (ulong)(xTop >> 63);')
        negate('y', load_v, vcount, 'g', signed)
        w('        carry = 0;')
        for i in range(vcount):
            if i == vcount-1 and not need_top:
                w(f'        ulong t{i} = yFactor * y{i} + p{i} + carry;')
            else:
                w(f'        carry = MulAdd(yFactor, y{i}, p{i}, carry, out ulong t{i});')
        if need_top:
            x_top = '(xTop >> 63)' if ucount < result_count else 'xTop'
            w(f'        long top = {x_top} + (long)carry + (long)yFactor * yExtension;')

    w('// Ported from blst, copyright Supranational LLC, Apache-2.0.\n// Generated by scripts/generate-inverse.py; see docs/design.md for bounds.\nusing System.Numerics;\nusing System.Runtime.CompilerServices;\n\nnamespace Nethermind.Crypto.BlsNet.Arithmetic;\n')
    w(f'public readonly partial struct {name}\n{{')
    w('    /// <summary>Secret inverse using fixed blst binary-GCD batches. Zero maps to zero; permits aliases.</summary>')
    w(f'    {opt}\n    public static void InverseConstantTime(out {name} result, in {name} value)\n    {{')
    w(f'        {name} a = value, b = new({args("M")});')
    for first in range(2):
        w('        InverseApproximate(a, b, out ulong aa, out ulong bb);' if first == 0 else '        InverseApproximate(a, b, out aa, out bb);')
        w('        InverseBatch.Steps31(aa, bb, out long f0, out long g0, out long f1, out long g1);' if first == 0 else '        InverseBatch.Steps31(aa, bb, out f0, out g0, out f1, out g1);')
        w(f'        InverseUpdate(out {name if first == 0 else ""} nextA, a, b, ref f0, ref g0);'.replace('out  nextA', 'out nextA'))
        w('        InverseUpdate(out b, a, b, ref f1, ref g1); a = nextA;')
        if first == 0: w('        long firstU = f0, firstV = f1;')
    w('        InverseInit(out InverseNarrow u, firstU * f0 + firstV * g0);\n        InverseInit(out InverseNarrow v, firstU * f1 + firstV * g1);')
    w(f'        for (int batch = 2; batch <= {narrow_last}; batch++)\n        {{')
    w('            InverseApproximate(a, b, out aa, out bb);\n            InverseBatch.Steps31(aa, bb, out f0, out g0, out f1, out g1);\n            InverseUpdate(out nextA, a, b, ref f0, ref g0);\n            InverseUpdate(out b, a, b, ref f1, ref g1); a = nextA;\n            InverseCoefficientNarrow(out InverseNarrow nextU, u, v, f0, g0);\n            InverseCoefficientNarrow(out v, u, v, f1, g1); u = nextU;\n        }')
    w('        InverseExtend(out InverseWide wideV, v);')
    for start, end, short in ([(12,19,False),(19,23,True)] if name == 'Fp' else [(9,15,False)]):
        w(f'        for (int batch = {start}; batch < {end}; batch++)\n        {{')
        suffix = '191' if short else ''
        w(f'            InverseApproximate{suffix}(a, b, out aa, out bb);\n            InverseBatch.Steps31(aa, bb, out f0, out g0, out f1, out g1);\n            InverseUpdate{suffix}(out nextA, a, b, ref f0, ref g0);\n            InverseUpdate{suffix}(out b, a, b, ref f1, ref g1); a = nextA;\n            InverseCoefficientKeep(out InverseNarrow nextU, u, wideV, f0, g0);\n            InverseCoefficientWide(out wideV, u, wideV, f1, g1); u = nextU;\n        }}')
    w(f'        InverseBatch.Finish(a._l0, b._l0, {remaining}, out long f, out long g);\n        long top = InverseCoefficientWide(out wideV, u, wideV, f, g);\n        InverseCorrect(out result, wideV, top);\n    }}\n')
    w(f'    {inline}\n    private static void InverseInit(out InverseNarrow result, long value)\n    {{\n        result.L0 = (ulong)value;')
    for i in range(1,n+1): w(f'        result.L{i} = (ulong)(value >> 63);')
    w('    }\n')
    w(f'    {inline}\n    private static void InverseExtend(out InverseWide result, in InverseNarrow value)\n    {{')
    for i in range(2*n): w(f'        result.L{i} = value.L{i};' if i <= n else f'        result.L{i} = (ulong)((long)value.L{n} >> 63);')
    w('    }\n')

    for words in ([n,3] if name == 'Fp' else [n]):
        suffix = '' if words == n else '191'
        w(f'    {inline}\n    internal static void InverseApproximate{suffix}(in {name} a, in {name} b, out ulong aa, out ulong bb)\n    {{')
        w(f'        ulong ah = a._l{words-1}, al = a._l{words-2}, bh = b._l{words-1}, bl = b._l{words-2}, mask;')
        for i in range(words-3,-1,-1):
            w(f'        mask = InverseBatch.ZeroMask(ah | bh);\n        ah = InverseBatch.Select(al, ah, mask); bh = InverseBatch.Select(bl, bh, mask);\n        al = InverseBatch.Select(a._l{i}, al, mask); bl = InverseBatch.Select(b._l{i}, bl, mask);')
        w('        mask = InverseBatch.ZeroMask(ah | bh);\n        int shift = BitOperations.LeadingZeroCount(ah | bh) & 63;\n        ah = InverseBatch.Select(a._l0, ah, mask); bh = InverseBatch.Select(b._l0, bh, mask);\n        ulong shifted = ~InverseBatch.ZeroMask((ulong)shift);\n        aa = ((ah << shift) | ((al & shifted) >> (-shift & 63))) & 0xffffffff80000000;\n        bb = ((bh << shift) | ((bl & shifted) >> (-shift & 63))) & 0xffffffff80000000;\n        aa |= a._l0 & 0x7fffffff; bb |= b._l0 & 0x7fffffff;\n    }\n')
        w(f'    {opt}\n    internal static void InverseUpdate{suffix}(out {name} result, in {name} a, in {name} b, ref long f, ref long g)\n    {{')
        sum_products(words, words, words, lambda i:f'a._l{i}', lambda i:f'b._l{i}', False, True)
        w(f'        ulong t{words} = (ulong)top, mask = (ulong)(top >> 63);\n        f = (f ^ (long)mask) - (long)mask; g = (g ^ (long)mask) - (long)mask;\n        ulong c = mask & 1;')
        for i in range(words):w(f'        ulong r{i} = AddCarry(((t{i} >> 31) | (t{i+1} << 33)) ^ mask, 0, ref c);')
        w(f'        result = {constructor("r", words)};\n    }}\n')

    for method, vtype, wide in [('Narrow','InverseNarrow',False),('Keep','InverseWide',False),('Wide','InverseWide',True)]:
        rtype = 'InverseWide' if wide else 'InverseNarrow'
        rettype = 'long' if wide else 'void'
        w(f'    {opt}\n    internal static {rettype} InverseCoefficient{method}(out {rtype} result, in InverseNarrow u, in {vtype} v, long f, long g)\n    {{')
        count = 2*n if wide else n+1
        sum_products(n+1, count, count, lambda i:f'u.L{i}', lambda i:f'v.L{i}', True, wide)
        for i in range(count): w(f'        result.L{i} = t{i};')
        if wide: w('        return top;')
        w('    }\n')

    # Correction is generated below with the same fixed full-range bounds.
    w(f'    {opt}\n    internal static void InverseCorrect(out {name} result, in InverseWide value, long top)\n    {{\n        // blst modx: modulus left-aligned within one field width. The final\n        // cofactor lies in [-2^(2N),2^(2N)]; top is -1, 0 or 1.\n        ulong sign = (ulong)(top >> 63), c = 0;')
    xs = [(modulus << align >> (64*i)) & (2**64-1) for i in range(n)]
    for i,x in enumerate(xs): w(f'        const ulong X{i} = 0x{x:016x}UL;')
    for i in range(n): w(f'        ulong h{i} = AddCarry(value.L{n+i}, X{i} & sign, ref c);')
    w('        top += (long)c;\n        ulong adjust = ~InverseBatch.ZeroMask((ulong)top);\n        sign = (ulong)(-top >> 63);\n        c = sign & 1;')
    for i in range(n): w(f'        ulong x{i} = AddCarry((X{i} & adjust) ^ sign, 0, ref c);')
    w('        c = 0;')
    for i in range(n): w(f'        h{i} = AddCarry(h{i}, x{i}, ref c);')
    w('        // Corrected value is in [0,R^2). Canonicalize its high half\n        // before REDC, so the sum with REDC(low) is below 2*modulus.')
    for bit in reversed(range(align+1)):
        w('        ulong borrow' + str(bit) + ' = 0;')
        for i in range(n):
            x=(modulus<<bit>>(64*i)) & (2**64-1)
            w(f'        ulong s{bit}_{i} = SubBorrow(h{i}, 0x{x:016x}UL, ref borrow{bit});')
        w(f'        ulong mask{bit} = borrow{bit} - 1;')
        for i in range(n): w(f'        h{i} = InverseBatch.Select(s{bit}_{i}, h{i}, mask{bit});')
    for i in range(n): w(f'        ulong t{i} = value.L{i};')
    w(f'        for (int row = 0; row < {n}; row++)\n        {{\n            ulong q = t0 * N0;\n            ulong carry = MulAdd(q, M0, t0, 0, out _);')
    for i in range(1,n): w(f'            carry = MulAdd(q, M{i}, t{i}, carry, out t{i-1});')
    w(f'            t{n-1} = carry;\n        }}\n        c = 0;')
    for i in range(n): w(f'        h{i} = AddCarry(h{i}, t{i}, ref c);')
    w(f'        Reduce(out {name} reduced, {args("h")});')
    r2 = 'R2' if name=='Fp' else 'new Fr(0xc999e990f3f29c6d, 0x2b6cedcb87925c23, 0x05d314967254398f, 0x0748d9d99f59ff11)'
    w(f'        // T=2N steps give v*input=R^2 modulo the modulus. REDC then\n        // multiplication by R^2 restores the inverse Montgomery representation.\n        Multiply(out result, reduced, {r2});\n    }}\n')
    for typename, size in [('InverseNarrow', n+1), ('InverseWide', 2*n)]:
        w(f'    internal struct {typename}\n    {{')
        for i in range(size): w(f'        internal ulong L{i};')
        w('    }')
    w('}')
    (root / f'{name}.InverseConstantTime.cs').write_text('\n'.join(lines)+'\n', encoding='utf-8')
