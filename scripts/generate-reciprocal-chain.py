"""Port the pinned blst reciprocal addition chain; run from the repository root."""
from pathlib import Path
import re

source = Path('external/blst/src/recip-addchain.h').read_text()
lines = []
for line in source.splitlines():
    if line.startswith('vec_copy(t[1],'):
        lines.append('        t[1] = value;')
    elif match := re.match(r'(sqr_n_mul|sqr|mul)\((.*?)\);', line):
        op, operands = match.groups()
        args = operands.split(', ')
        args = ['result' if arg == 'out' else arg for arg in args]
        if op == 'sqr_n_mul':
            dst, src, count, factor = args
            lines.append(f'        Fp.SquareNThenMultiply(out {dst}, {src}, {count}, {factor});')
        elif op == 'sqr':
            lines.append(f'        CurveField<Fp>.Square(out {args[0]}, {args[1]});')
        else:
            lines.append(f'        Fp.MultiplyComposite(out {args[0]}, {args[1]}, {args[2]});')

Path('src/Nethermind.Crypto.BlsNet/Arithmetic/Fp.ReciprocalChain.cs').write_text('''// Ported from blst recip-addchain.h, copyright Supranational LLC, Apache-2.0.
// Generated by scripts/generate-reciprocal-chain.py; 460 field operations.
using System.Runtime.CompilerServices;
using Nethermind.Crypto.BlsNet.Curves;

namespace Nethermind.Crypto.BlsNet.Arithmetic;

public readonly partial struct Fp
{
    /// <summary>Secret field inverse, with the fixed blst p-2 chain. Zero maps to zero; permits aliases.</summary>
    [MethodImpl(MethodImplOptions.NoInlining | MethodImplOptions.AggressiveOptimization)]
    public static void InverseConstantTime(out Fp result, in Fp value)
    {
        Span<Fp> t = stackalloc Fp[16];
''' + '\n'.join(lines) + '\n    }\n}\n')
